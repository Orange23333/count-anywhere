class Kernel32:
    @staticmethod
    def GetLastError() -> ctypes.wintypes.DWORD:
        """
        Retrieves the calling thread's last-error code value. The last-error code is maintained on a per-thread basis.
        Multiple threads do not overwrite each other's last-error code.

        ---

        Functions executed by the calling thread set this value by calling the SetLastError function.
        You should call the GetLastError function immediately when a function's return value indicates that such a
        call will return useful data. That is because some functions call SetLastError with a zero when they succeed,
        wiping out the error code set by the most recently failed function.

        To obtain an error string for system error codes, use the FormatMessage function. For a complete list of
        error codes provided by the operating system, see System Error Codes.

        The error codes returned by a function are not part of the Windows API specification and can vary by
        operating system or device driver. For this reason, we cannot provide the complete list of error codes that
        can be returned by each function. There are also many functions whose documentation does not include even a
        partial list of error codes that can be returned.

        Error codes are 32-bit values (bit 31 is the most significant bit). Bit 29 is reserved for
        application-defined error codes; no system error code has this bit set. If you are defining an error code for
        your application, set this bit to one. That indicates that the error code has been defined by an application,
        and ensures that your error code does not conflict with any error codes defined by the system.

        To convert a system error into an HRESULT value, use the HRESULT_FROM_WIN32 macro.

        :return:
        The return value is the calling thread's last-error code.

        The Return Value section of the documentation for each function that sets the last-error code notes the
        conditions under which the function sets the last-error code. Most functions that set the thread's last-error
        code set it when they fail. However, some functions also set the last-error code when they succeed.
        If the function is not documented to set the last-error code, the value returned by this function is simply
        the most recent last-error code to have been set; some functions set the last-error code to 0 on success and
        others do not.
        """

        return ctypes.windll.kernel32.GetLastError()


class User32:
    @deprecated('Not implemented as expectation.')
    @staticmethod
    def GetKeyboardState(
            lpKeyState: ctypes.wintypes.PBYTE | list
    ) -> ctypes.wintypes.BOOL:
        """
        Copies the status of the 256 virtual keys to the specified buffer.

        ---

        An application can call this function to retrieve the current status of all the virtual keys.
        The status changes as a thread removes keyboard messages from its message queue. The status does not change as
        keyboard messages are posted to the thread's message queue, nor does it change as keyboard messages are
        posted to or retrieved from message queues of other threads. (Exception: Threads that are connected through
        AttachThreadInput share the same keyboard state.)

        When the function returns, each member of the array pointed to by the lpKeyState parameter contains
        status data for a virtual key. If the high-order bit is 1, the key is down; otherwise, it is up.
        If the key is a toggle key, for example CAPS LOCK, then the low-order bit is 1 when the key is toggled and
        is 0 if the key is untoggled. The low-order bit is meaningless for non-toggle keys. A toggle key is said to be
        toggled when it is turned on. A toggle key's indicator light (if any) on the keyboard will be on when the key is
        toggled, and off when the key is untoggled.

        To retrieve status information for an individual key, use the GetKeyState function. To retrieve the
        current state for an individual key regardless of whether the corresponding keyboard message has been
        retrieved from the message queue, use the GetAsyncKeyState function.

        An application can use the virtual-key code constants VK_SHIFT, VK_CONTROL and VK_MENU as indices into the
        array pointed to by lpKeyState. This gives the status of the SHIFT, CTRL, or ALT keys without
        distinguishing between left and right. An application can also use the following virtual-key code constants as
        indices to distinguish between the left and right instances of those keys: VK_LSHIFT, VK_RSHIFT, VK_LCONTROL,
        VK_RCONTROL, VK_LMENU, VK_RMENU.

        These left- and right-distinguishing constants are available to an application only through the
        GetKeyboardState, SetKeyboardState, GetAsyncKeyState, GetKeyState, and MapVirtualKey functions.

        :return:
        If the function succeeds, the return value is nonzero.

        If the function fails, the return value is zero. To get extended error information, call GetLastError.

        :prarm lpKeyState: [out]
        The 256-byte array that receives the status data for each virtual key.
        """

        raise NotImplementedError()

        if isinstance(lpKeyState, list):
            _ArrayType = ctypes.wintypes.BYTE * 256
            arr = _ArrayType(*[0 for _ in range(256)])
            ctypes.wintypes.PBYTE(arr)

        ret = ctypes.windll.user32.GetKeyboardState(lpKeyState)

        if isinstance(lpKeyState, list) and ret != 0:
            lpKeyState.clear()
            for x in arr:
                lpKeyState.append(x)

        return ret

