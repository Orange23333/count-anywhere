    @staticmethod
    def RegisterHotKey(
            hWnd: ctypes.wintypes.HWND | None,
            id_: ctypes.c_int32,
            fsModifiers: ctypes.wintypes.UINT | Winuser.SystemMessage.WM_HOTKEY.lParam,
            vk: ctypes.wintypes.UINT | Winuser.VirtualKeyCodeType
    ) -> ctypes.wintypes.BOOL:
        """
        Defines a system-wide hot key.

        ---

        When a key is pressed, the system looks for a match against all hot keys. Upon finding a match, the
        system posts the WM_HOTKEY message to the message queue of the window with which the hot key is associated.
        If the hot key is not associated with a window, then the WM_HOTKEY message is posted to the
        thread associated with the hot key.

        If a hot key already exists with the same hWnd and id parameters, it is maintained along with the new hot key.
        The application must explicitly call UnregisterHotKey to unregister the old hot key.

        The F12 key is reserved for use by the debugger at all times, so it should not be registered as a hot key.
        Even when you are not debugging an application, F12 is reserved in case a kernel-mode debugger or a
        just-in-time debugger is resident.

        An application must specify an id value in the range 0x0000 through 0xBFFF. A shared DLL must specify a
        value in the range 0xC000 through 0xFFFF (the range returned by the GlobalAddAtom function). To avoid
        conflicts with hot-key identifiers defined by other shared DLLs, a DLL should use the GlobalAddAtom function to
        obtain the hot-key identifier.

        Windows Server 2003: If a hot key already exists with the same hWnd and id parameters, it is replaced by the
        new hot key.

        :return:
        If the function succeeds, the return value is nonzero.

        If the function fails, the return value is zero. To get extended error information, call GetLastError.

        This function fails if you try to associate a hot key with a window created by another thread.

        Typically, RegisterHotKey also fails if the keystrokes specified for the hot key have already been
        registered for another hot key. However, some pre-existing, default hotkeys registered by the OS (such as
        PrintScreen, which launches the Snipping tool) may be overridden by another hot key registration when one of
        the app's windows is in the foreground.

        :param hWnd: [in, optional]
        A handle to the window that will receive WM_HOTKEY messages generated by the hot key. If this parameter is NULL,
        WM_HOTKEY messages are posted to the message queue of the calling thread and must be processed in
        the message loop.

        :param id_: [in]
        The identifier of the hot key. If the hWnd parameter is NULL, then the hot key is associated with the
        current thread rather than with a particular window. If a hot key already exists with the same hWnd and
        id parameters, see Remarks for the action taken.

        :param fsModifiers: [in]
        The keys that must be pressed in combination with the key specified by the vk parameter in order to generate the
        WM_HOTKEY message.

        :param vk: [in]
        The virtual-key code of the hot key. See Virtual Key Codes.
        """

        if hWnd is None:
            hWnd = ctypes.wintypes.HWND(None)
        if isinstance(fsModifiers, Winuser.SystemMessage.WM_HOTKEY.lParam):
            fsModifiers = ctypes.wintypes.UINT(fsModifiers.value)
        if isinstance(vk, Winuser.VirtualKeyCode):
            vk = ctypes.wintypes.UINT(vk.value)
        elif isinstance(vk, str):
            if len(vk) != 1:
                raise SyntaxError('vk must be a single character.')

            vk = ord(vk)

            if not (
                ord('0') <= vk <= ord('9') or
                ord('A') <= vk <= ord('Z') or
                ord('a') <= vk <= ord('z')
            ):
                raise SyntaxError('vk must be an alphabetic or numeric character.')

            vk = ctypes.wintypes.UINT(vk)


        return ctypes.windll.user32.RegisterHotKey(hWnd, id_, fsModifiers, vk)

    @staticmethod
    def UnregisterHotKey(
            hWnd: ctypes.wintypes.HWND | None,
            id_: ctypes.c_int32
    ) -> ctypes.wintypes.BOOL:
        """
        Frees a hot key previously registered by the calling thread.

        :return:
        If the function succeeds, the return value is nonzero.

        If the function fails, the return value is zero. To get extended error information, call GetLastError.

        :param hWnd: [in, optional]
        A handle to the window associated with the hot key to be freed. This parameter should be NULL if the
        hot key is not associated with a window.

        :param id_: [in]
        The identifier of the hot key to be freed.
        """

        if hWnd is None:
            hWnd = ctypes.wintypes.HWND(None)

        return ctypes.windll.user32.UnregisterHotKey(hWnd, id_)
